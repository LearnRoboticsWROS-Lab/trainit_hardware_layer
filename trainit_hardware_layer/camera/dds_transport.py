"""How a camera's large images cross DDS on the ACQUISITION host (ROS-free; used by the real camera launch).

Why it exists. ROS 2 Humble's default middleware is Fast DDS 2.6. Between two processes of one host it carries data
through shared memory, in a segment of 512 KiB per participant by default. A best-effort image larger than that
segment (848x480 colour = 1.2 MB, aligned depth = 0.8 MB) is lost whenever the segment is still busy: measured on the
development workstation (2026-10-30, D0-C), the driver produced 30 depth frames/s while a subscriber on the same host
received 5.7 to 11/s, with gaps of up to 0.67 s -- and nothing reported an error. With the driver's segment large
enough for 16 framesets, the same subscriber received 30.0/s with no gap.

What it does. For the DRIVER process only (the publisher of the large images; a subscriber needs nothing), the launch
gives Fast DDS a profile whose shared-memory segment holds ``FRAMESETS_HELD`` framesets of the configured streams. The
size is COMPUTED from the hardware profile (resolution, enabled streams, point cloud), so any RealSense model and
resolution gets its own size; it is capped at a share of the host's ``/dev/shm`` (a container's default is 64 MiB).
UDPv4 stays enabled: subscribers on other hosts are unaffected. Nothing on the host is changed (no sysctl, no global
file): the profile is a generated, content-addressed file under ``$ROS_HOME/trainit/fastdds`` and only the driver's
environment points at it.

It never overrides a choice the user made: a Fast DDS profile already set in the environment is kept as is, and
another middleware (``RMW_IMPLEMENTATION``) is left alone. Every outcome is a JSON-plain decision that the source
information records (``deployment.dds_transport``, DECLARED by the launch).
"""
import hashlib
import math
import os
from pathlib import Path

FASTDDS_RMWS = ('rmw_fastrtps_cpp', 'rmw_fastrtps_dynamic_cpp')
PROFILE_ENV = 'FASTRTPS_DEFAULT_PROFILES_FILE'                       # the variable Fast DDS 2.x reads
USER_PROFILE_ENVS = (PROFILE_ENV, 'FASTDDS_DEFAULT_PROFILES_FILE')  # either one set by the user is the user's choice
FASTDDS_DEFAULT_SEGMENT_BYTES = 512 * 1024
FRAMESETS_HELD = 16                 # a subscriber may lag about half a second at 30 fps before a frame is lost
FRAMESETS_FLOOR = 4                 # below this many framesets the launch log warns that frames may be lost
DEV_SHM_SHARE = 4                   # the segment takes at most 1/4 of the host's /dev/shm
MIB = 1 << 20
BYTES_PER_PIXEL = {'color': 3, 'depth': 2}       # RGB8 and Z16: the formats the real launch requests
POINT_BYTES = 16                                 # the driver's XYZRGB point: x, y, z and packed rgb (measured)
REQUESTS = ('auto', 'off')
MODES = ('APPLIED', 'USER_PROFILE', 'OTHER_RMW', 'OFF', 'NOT_APPLIED')


def frameset_bytes(prof, pointcloud=False) -> int:
    """Bytes the driver process publishes per frameset: colour + aligned depth, + its own point cloud when enabled
    (at most one point per depth pixel: an upper bound, the driver keeps only valid points)."""
    color, depth = prof['sensor']['color'], prof['sensor']['depth']
    total = color['width'] * color['height'] * BYTES_PER_PIXEL['color']
    total += color['width'] * color['height'] * BYTES_PER_PIXEL['depth']        # aligned depth: the colour's grid
    if pointcloud:
        total += depth['width'] * depth['height'] * POINT_BYTES
    return total


def segment_bytes(frameset: int, dev_shm_bytes=None):
    """(segment size, capped): ``FRAMESETS_HELD`` framesets rounded up to MiB, at most 1/``DEV_SHM_SHARE`` of
    ``/dev/shm`` when its size is known (never below the Fast DDS default). The cap uses the TOTAL size of
    ``/dev/shm``, not what is free at launch time."""
    wanted = math.ceil(FRAMESETS_HELD * frameset / MIB) * MIB
    if dev_shm_bytes:
        cap = (dev_shm_bytes // DEV_SHM_SHARE) // MIB * MIB
        if wanted > cap:
            return max(cap, FASTDDS_DEFAULT_SEGMENT_BYTES), True
    return wanted, False


def profile_xml(segment: int) -> str:
    """The Fast DDS profile: a shared-memory transport with ``segment`` bytes, plus the default UDPv4 transport."""
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by trainit_hardware_layer (camera/dds_transport.py) for a camera driver process. Do not edit. -->
<profiles xmlns="http://www.eprosima.com/XMLSchemas/fastRTPS_Profiles">
  <transport_descriptors>
    <transport_descriptor>
      <transport_id>trainit_camera_shm</transport_id>
      <type>SHM</type>
      <segment_size>{int(segment)}</segment_size>
    </transport_descriptor>
    <transport_descriptor>
      <transport_id>trainit_camera_udp</transport_id>
      <type>UDPv4</type>
    </transport_descriptor>
  </transport_descriptors>
  <participant profile_name="trainit_camera_driver" is_default_profile="true">
    <rtps>
      <userTransports>
        <transport_id>trainit_camera_shm</transport_id>
        <transport_id>trainit_camera_udp</transport_id>
      </userTransports>
      <useBuiltinTransports>false</useBuiltinTransports>
    </rtps>
  </participant>
</profiles>
'''


def profile_directory(environ) -> Path:
    """Where generated profiles live: ``$ROS_HOME/trainit/fastdds`` (``~/.ros`` when ``ROS_HOME`` is unset)."""
    home = environ.get('ROS_HOME') or os.path.join(os.path.expanduser('~'), '.ros')
    return Path(home) / 'trainit' / 'fastdds'


def write_profile(text: str, directory: Path) -> Path:
    """The profile file for ``text``: content-addressed, written atomically, reused when it already exists."""
    digest = hashlib.sha256(text.encode('utf-8')).hexdigest()
    path = Path(directory) / f'trainit_camera_{digest[:16]}.xml'
    if path.is_file() and path.read_text(encoding='utf-8') == text:
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f'.{path.name}.{os.getpid()}.tmp')
    try:
        temporary.write_text(text, encoding='utf-8')
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()
    return path


def dev_shm_bytes(path='/dev/shm'):
    """The size of the host's shared-memory filesystem, else ``None``."""
    try:
        stat = os.statvfs(path)
    except OSError:
        return None
    return stat.f_blocks * stat.f_frsize or None


def configure(requested, prof, *, pointcloud, rmw, environ, shm_bytes, directory):
    """(decision, driver environment) for one camera driver.

    ``requested``: ``auto`` | ``off``. ``rmw``: the middleware the driver will run with (``None`` when it could not
    be established: the profile is then still set -- any other middleware ignores it -- and the decision says so).
    ``environ``: the launch context's environment (what the driver inherits). ``shm_bytes``: ``/dev/shm`` size
    (``None`` = unknown). ``directory``: where the generated profile goes. The decision is JSON-plain; the
    environment is what the DRIVER process gets added (empty unless the profile is applied).
    """
    if requested not in REQUESTS:
        raise ValueError(f'dds_transport must be one of {REQUESTS}, got {requested!r}')
    decision = {'rmw': rmw} if rmw else {}
    if requested == 'off':
        return dict(decision, mode='OFF'), {}
    user = next((name for name in USER_PROFILE_ENVS if environ.get(name)), None)
    if user:
        return dict(decision, mode='USER_PROFILE', variable=user), {}
    if rmw and rmw not in FASTDDS_RMWS:
        return dict(decision, mode='OTHER_RMW'), {}
    frameset = frameset_bytes(prof, pointcloud)
    segment, capped = segment_bytes(frameset, shm_bytes)
    text = profile_xml(segment)
    try:
        path = write_profile(text, directory)
    except OSError as exc:
        return dict(decision, mode='NOT_APPLIED', reason=f'the profile could not be written ({exc.strerror})'), {}
    decision.update(mode='APPLIED', shm_segment_bytes=segment, frameset_bytes=frameset,
                    framesets_held=segment // frameset, capped_by_dev_shm=capped,
                    profile_sha256=hashlib.sha256(text.encode('utf-8')).hexdigest())
    if not rmw:
        decision['note'] = 'the middleware was not established: the profile takes effect only if it is Fast DDS'
    return decision, {PROFILE_ENV: str(path)}


def describe(decision) -> str:
    """One line for the launch log."""
    mode = decision.get('mode')
    if mode == 'APPLIED':
        held = decision['framesets_held']
        line = (f'Fast DDS shared-memory segment {decision["shm_segment_bytes"] / MIB:g} MiB for the camera driver '
                f'({held} framesets of {decision["frameset_bytes"] / 1e6:.1f} MB; default '
                f'{FASTDDS_DEFAULT_SEGMENT_BYTES // 1024} KiB)')
        if held < 1:
            line += ' -- CAPPED by /dev/shm below ONE frameset: images WILL be lost (enlarge /dev/shm)'
        elif decision['capped_by_dev_shm'] and held < FRAMESETS_FLOOR:
            line += ' -- CAPPED by /dev/shm: a slow subscriber will lose images (enlarge /dev/shm)'
        elif decision['capped_by_dev_shm']:
            line += ' -- capped by /dev/shm'
        if decision.get('note'):
            line += f' ({decision["note"]})'
        return line
    if mode == 'USER_PROFILE':
        return (f'the Fast DDS profile in {decision["variable"]} is kept: its shared-memory segment must hold the '
                'camera framesets or images are lost (contracts/camera.md, "Large images on one host")')
    if mode == 'OTHER_RMW':
        return f'middleware {decision.get("rmw")}: no Fast DDS profile applied (configure large messages for it)'
    if mode == 'OFF':
        return 'dds_transport:=off: Fast DDS defaults (512 KiB shared-memory segment): large images may be lost'
    return f'no Fast DDS profile applied: {decision.get("reason")}'


